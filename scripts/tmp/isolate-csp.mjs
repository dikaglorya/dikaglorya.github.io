import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 1200, height: 900 }, permissions: ['clipboard-read','clipboard-write'] });
const p = await ctx.newPage();
const errors = [];
p.on('console', m => { if (m.type() === 'error') errors.push(m.text().slice(0,120)); });
p.on('pageerror', e => errors.push('PAGEERROR ' + e.message.slice(0,120)));
await p.goto('http://127.0.0.1:4321/contact/', { waitUntil: 'networkidle' });
console.log('after load:', errors.length, errors.slice(0,2));
await p.fill('#name','Dika');
await p.fill('#email','dika@example.com');
await p.selectOption('#service','website');
await p.fill('#message','Tes');
console.log('after fill:', errors.length);
await p.click('button[type=submit]');
await p.waitForSelector('[data-brief-ready]:not([hidden])');
await p.waitForTimeout(300);
console.log('after submit:', errors.length, errors.slice(0,2));
await browser.close();
